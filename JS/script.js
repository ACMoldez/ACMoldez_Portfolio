const targetElement = document.getElementById("rotating-text");
const yearElement = document.getElementById("current-year");
const modal = document.getElementById("story-modal");
const modalTitle = document.getElementById("story-modal-title");
const modalText = document.getElementById("story-modal-text");
const dialogueTranscript = document.getElementById("dialogue-transcript");
const dialogueChoices = document.getElementById("dialogue-choices");
const dialoguePromptLabel = document.getElementById("dialogue-prompt-label");
const dialogueComplete = document.getElementById("dialogue-complete");
const closeModalButton = document.querySelector(".modal-close");
const questCounter = document.getElementById("quest-counter");
const questMessage = document.getElementById("quest-message");
const progressFill = document.getElementById("progress-fill");
const progressBar = document.querySelector(".progress-bar");
const inventoryPills = document.querySelectorAll(".inventory-pill");
const storyButtons = document.querySelectorAll(".story-card");

const unlockedStories = new Set();
let lastFocusedElement = null;
let replyTimeout = null;
let typingTimeout = null;
const replyDelay = 1600;
const typingSpeed = 18;

if (yearElement) {
  yearElement.textContent = new Date().getFullYear();
}

if (targetElement) {
  let currentIndex = 0;

  function changeSubheading() {
    targetElement.classList.remove("slide-fade-animation");
    void targetElement.offsetWidth;

    currentIndex = (currentIndex + 1) % subheadings.length;
    targetElement.textContent = subheadings[currentIndex];
    targetElement.classList.add("slide-fade-animation");
  }

  targetElement.classList.add("slide-fade-animation");
  setInterval(changeSubheading, 3000);
}

function updateQuestBoard() {
  const total = storyButtons.length;
  const unlockedCount = unlockedStories.size;
  const progress = (unlockedCount / total) * 100;

  if (questCounter) {
    questCounter.textContent = `${unlockedCount} / ${total} unlocked`;
  }

  if (progressFill) {
    progressFill.style.width = `${progress}%`;
  }

  if (progressBar) {
    progressBar.setAttribute("aria-valuemax", String(total));
    progressBar.setAttribute("aria-valuenow", String(unlockedCount));
  }

  if (questMessage) {
    if (unlockedCount === 0) {
      questMessage.textContent = "Explore the story archive to reveal my world.";
    } else if (unlockedCount === total) {
      questMessage.textContent = "All story quests complete — welcome to my world.";
    } else {
      questMessage.textContent = `Nice! ${unlockedCount} chapter${unlockedCount > 1 ? "s" : ""} unlocked.`;
    }
  }
}

function unlockStoryTrait(key) {
  inventoryPills.forEach((pill) => {
    if (pill.dataset.pill === key) {
      pill.classList.add("active");
    }
  });
}

function createDialogueChoice(item, isFollowUp = false) {
  const choice = document.createElement("button");
  choice.className = isFollowUp
    ? "dialogue-choice dialogue-choice-followup"
    : "dialogue-choice";
  choice.type = "button";
  choice.textContent = item.question;
  choice.addEventListener("click", () => answerStory(item, choice));
  return choice;
}

function openStory(key) {
  if (
    !modal ||
    !modalTitle ||
    !modalText ||
    !dialogueTranscript ||
    !dialogueChoices ||
    !dialoguePromptLabel ||
    !dialogueComplete
  ) {
    return;
  }

  const content = storyContent[key];
  if (!content) return;
  window.clearTimeout(replyTimeout);
  window.clearTimeout(typingTimeout);
  replyTimeout = null;
  typingTimeout = null;

  if (!unlockedStories.has(key)) {
    unlockedStories.add(key);
    updateQuestBoard();
    unlockStoryTrait(key);
  }

  lastFocusedElement = document.activeElement;
  modalTitle.textContent = content.title;
  modalText.textContent = content.intro;
  dialogueTranscript.replaceChildren(modalText);
  dialogueChoices.replaceChildren();
  dialoguePromptLabel.textContent = "Pick something you're curious about:";
  dialogueComplete.classList.add("hidden");

  content.questions.forEach((item) => {
    dialogueChoices.appendChild(createDialogueChoice(item));
  });

  modal.classList.remove("hidden");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  dialogueChoices.querySelector("button")?.focus();
}

function answerStory(item, choice) {
  if (!dialogueTranscript || !dialogueChoices || !dialogueComplete || !dialoguePromptLabel) return;

  const question = document.createElement("p");
  question.className = "dialogue-line visitor-line";
  question.textContent = item.question;

  choice.remove();
  dialogueChoices.querySelectorAll("button").forEach((button) => {
    button.disabled = true;
  });

  const thinking = document.createElement("p");
  thinking.className = "dialogue-line adrian-line thinking-line";
  thinking.setAttribute("role", "status");
  thinking.setAttribute("aria-label", "AC is thinking");
  thinking.append("AC is thinking");
  const dots = document.createElement("span");
  dots.className = "thinking-dots";
  dots.setAttribute("aria-hidden", "true");
  dots.textContent = "...";
  thinking.appendChild(dots);

  dialogueTranscript.append(question, thinking);
  dialogueTranscript.scrollTop = dialogueTranscript.scrollHeight;
  closeModalButton?.focus();

  replyTimeout = window.setTimeout(() => {
    replyTimeout = null;
    if (modal?.classList.contains("hidden")) return;

    const answer = document.createElement("p");
    answer.className = "dialogue-line adrian-line typing-answer";
    answer.setAttribute("aria-label", item.answer);
    answer.textContent = "";
    thinking.replaceWith(answer);
    const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    let characterIndex = 0;

    function typeNextCharacter() {
      if (modal?.classList.contains("hidden")) {
        typingTimeout = null;
        return;
      }

      if (characterIndex < item.answer.length) {
        answer.textContent += item.answer.charAt(characterIndex);
        characterIndex += 1;
        dialogueTranscript.scrollTop = dialogueTranscript.scrollHeight;
        typingTimeout = window.setTimeout(typeNextCharacter, typingSpeed);
        return;
      }

      answer.classList.remove("typing-answer");
      typingTimeout = null;

      if (item.followUps?.length) {
        [...item.followUps].reverse().forEach((followUp) => {
          dialogueChoices.insertBefore(
            createDialogueChoice(followUp, true),
            dialogueChoices.firstChild
          );
        });
        dialoguePromptLabel.textContent = "Want to ask a little more?";
      } else if (!dialogueChoices.querySelector(".dialogue-choice-followup")) {
        dialoguePromptLabel.textContent = dialogueChoices.querySelector("button")
          ? "Pick something else you're curious about:"
          : "You've heard the whole story.";
      }

      const nextChoice = dialogueChoices.querySelector("button");
      if (nextChoice) {
        dialogueChoices.querySelectorAll("button").forEach((button) => {
          button.disabled = false;
        });
        nextChoice.focus();
      } else {
        dialogueComplete.classList.remove("hidden");
        closeModalButton?.focus();
      }
    }

    if (prefersReducedMotion) {
      answer.textContent = item.answer;
      characterIndex = item.answer.length;
      typeNextCharacter();
    } else {
      typeNextCharacter();
    }
  }, replyDelay);
}

function closeStory() {
  if (!modal) return;
  window.clearTimeout(replyTimeout);
  window.clearTimeout(typingTimeout);
  replyTimeout = null;
  typingTimeout = null;
  modal.classList.add("hidden");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
  lastFocusedElement?.focus();
}

storyButtons.forEach((button) => {
  button.addEventListener("click", () => {
    openStory(button.dataset.story);
    button.classList.add("is-unlocked");
  });
});

if (closeModalButton) {
  closeModalButton.addEventListener("click", closeStory);
}

if (modal) {
  modal.addEventListener("click", (event) => {
    if (event.target === modal) {
      closeStory();
    }
  });
}

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && modal && !modal.classList.contains("hidden")) {
    closeStory();
  }

  if (event.key === "Tab" && modal && !modal.classList.contains("hidden")) {
    const focusable = modal.querySelectorAll("button:not(:disabled)");
    const first = focusable[0];
    const last = focusable[focusable.length - 1];

    if (event.shiftKey && document.activeElement === first) {
      event.preventDefault();
      last.focus();
    } else if (!event.shiftKey && document.activeElement === last) {
      event.preventDefault();
      first.focus();
    }
  }
});

updateQuestBoard();
